export type LiquidityText = (key: LiquidityMessageKey, values?: Record<string, string | number>) => string
export function liquidityText(locale: Locale): LiquidityText {
  const messages: Messages = locale === 'en' ? en : locale === 'yue-HK' ? yue : zh
  return (key, values) =>
    Object.entries(values ?? {}).reduce(
      (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
      messages[key],
    )
}
